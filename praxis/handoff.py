"""Export a finished design's docs pack into a fresh, agent-ready project dir.

`praxis handoff <id> <target>` is the bridge between a stored design and an
external coding agent: it validates the design (same consistency checks as
``praxis check``), copies the allowlisted pack documents (the eleven core
files plus RECOMMENDATIONS.md when present) out of
``designs/<NNN>-<slug>/docs/``, writes the generated agent files
(HANDOFF_PROMPT.md, AGENTS.md, a stack-derived .gitignore, and optionally
``.cursor/rules/praxis.mdc`` via --cursor), secret-scans every file it
wrote or merged, and runs ``git init``. Nothing outside the allowlist ever
leaves the Praxis tree, and a hit in the final scan refuses to leave
key-like content behind.
"""

from __future__ import annotations

import os
import re
import shutil
import subprocess
import sys
from pathlib import Path

from praxis.config import load_facts
from praxis.consistency import SEVERITY_ERROR, run_checks
from praxis.db import get_design_meta, latest_blueprint, latest_design
from praxis.design import PROVENANCE_VERSION
from praxis.design_io import design_dir, load_passes
from praxis.planning import PACK_PASS_IDS

# The files `praxis plan` writes into docs/ (eleven core documents plus the
# optional RECOMMENDATIONS.md, copied only when present). Anything else in
# docs/ (stray .env, .pem, editor droppings) fails the handoff unless --force,
# and even then only allowlisted names are ever copied.
PACK_ALLOWLIST: tuple[str, ...] = (
    ".env.example",
    "ARCHITECTURE.md",
    "DECISIONS.md",
    "DESIGN.md",
    "MEMORY.md",
    "PRD.md",
    "README.md",
    "RECOMMENDATIONS.md",
    "RULES.md",
    "SECURITY.md",
    "TASKS.md",
    "TEST_PLAN.md",
)

# Provenance header shared by AGENTS.md and the .cursor rule: a pre-existing
# target file without it belongs to the user and is never overwritten.
_PRAXIS_HEADER = (
    "<!-- Generated by the Praxis tool from RULES.md; edit RULES.md, "
    "not this file -->"
)

_CURSOR_REL = Path(".cursor") / "rules" / "praxis.mdc"
_CURSOR_FRONTMATTER = (
    "---\n"
    "description: Praxis design rules (generated from RULES.md by the Praxis tool)\n"
    "alwaysApply: true\n"
    "---\n\n"
)

# Candidate read order for HANDOFF_PROMPT.md and the AGENTS.md workflow,
# rendered only for files handoff actually copied into the target.
_READ_ORDER: tuple[str, ...] = (
    "README.md",
    "PRD.md",
    "ARCHITECTURE.md",
    "DESIGN.md",
    "RECOMMENDATIONS.md",
    "RULES.md",
    "TASKS.md",
    "TEST_PLAN.md",
    "SECURITY.md",
    "DECISIONS.md",
    "MEMORY.md",
    ".env.example",
)

# Key-like content that must never reach a fresh repo. Prefixes require real
# key length, and assignments require a non-empty value, so placeholder
# names in .env.example ("NVIDIA_NIM_API_KEY=") and words like "task-" or
# "scikit-learn" can never match.
_KEY_PATTERNS: tuple[tuple[str, re.Pattern[str]], ...] = (
    ("gsk_", re.compile(r"gsk_[A-Za-z0-9]{8,}")),
    ("nvapi-", re.compile(r"nvapi-[A-Za-z0-9]{8,}")),
    ("sk-", re.compile(r"\bsk-[A-Za-z0-9]{8,}")),
    ("Bearer", re.compile(r"Bearer\s+[A-Za-z0-9\-_.]{8,}")),
    ("api_key=", re.compile(r"(?i)api[_-]?key\s*[=:]\s*[\"']?[A-Za-z0-9\-_]{8,}")),
)

# A matched value carrying one of these markers is a documented placeholder
# (packs ship lines like GROQ_API_KEY=gsk_local_development_key_placeholder),
# not a secret.
_PLACEHOLDER_MARKERS = (
    "placeholder",
    "example",
    "changeme",
    "change_me",
    "your_",
    "your-",
    "dummy",
    "sample",
    "xxxx",
    "<",
)

# ---- .gitignore (stack detection reads the PACK, never the facts sheet) ----

_GITIGNORE_MARKER = "# added by praxis handoff"

# Universal lines: emitted for every handoff, regardless of stack.
GITIGNORE_UNIVERSAL: tuple[str, ...] = (
    ".env",
    ".env.*",
    "!.env.example",
    "*.pem",
    "*.log",
    ".DS_Store",
    ".opencode/",
)

# Word-bounded markers searched inside ARCHITECTURE.md's `### Stack`
# section. Word boundaries keep lookalikes quiet: "trust", "robust",
# "pipeline", "reactive" and "nodes" fire nothing.
_STACK_MARKERS: dict[str, tuple[re.Pattern[str], ...]] = {
    "python": tuple(
        re.compile(p, re.I)
        for p in (r"\bpython\b", r"\bpyproject\b", r"\brequirements\.txt\b", r"\bpip\b")
    ),
    "node": tuple(
        re.compile(p, re.I)
        for p in (
            r"\bpackage\.json\b",
            r"\bnext\.js\b",
            r"\btypescript\b",
            r"\bjavascript\b",
            r"\bnode(?:\.js)?\b",
            r"\breact\b",
        )
    ),
    "rust": tuple(
        re.compile(p, re.I) for p in (r"\bcargo(?:\.toml)?\b", r"\brust\b")
    ),
}

# Whole-file fallback (ARCHITECTURE.md has no `### Stack` section): only
# the strong markers are accepted, still word-bounded.
_STRONG_MARKERS: dict[str, tuple[re.Pattern[str], ...]] = {
    "python": tuple(
        re.compile(p, re.I) for p in (r"\bpyproject\b", r"\brequirements\.txt\b")
    ),
    "node": tuple(
        re.compile(p, re.I)
        for p in (r"\bpackage\.json\b", r"\bnext\.js\b", r"\btypescript\b")
    ),
    "rust": tuple(re.compile(p, re.I) for p in (r"\bcargo\.toml\b",)),
}

_GITIGNORE_BLOCKS: dict[str, tuple[str, ...]] = {
    "python": (
        "__pycache__/",
        "*.py[cod]",
        ".venv/",
        ".pytest_cache/",
        ".ruff_cache/",
        ".mypy_cache/",
        "dist/",
        "*.egg-info/",
    ),
    "node": ("node_modules/", "dist/", "coverage/"),
    "nextjs": (".next/", "out/", ".vercel/", "*.tsbuildinfo"),
    "rust": ("target/",),
}

# Next.js-specific lines fire only on these two word-bounded spellings;
# the bare word "next" ("next step") never matches anything.
_NEXTJS_MARKERS: tuple[re.Pattern[str], ...] = (
    re.compile(r"\bnext\.js\b", re.I),
    re.compile(r"\bnextjs\b", re.I),
)

_SQLITE_RE = re.compile(r"\bsqlite\b", re.I)
_STACK_HEADING_RE = re.compile(r"^### Stack\s*$")
_ANY_HEADING_RE = re.compile(r"^#{1,3} ")

HANDOFF_PROMPT_TEMPLATE = """\
# Handoff: {title} (candidate {candidate_id})

You are a fresh coding-agent session starting this project in an empty git
repo. The design pack was exported by the Praxis tool.

## Workflow — plan mode first, no code yet

1. Read, in order: {read_list}.
2. Obey RULES.md constraints absolutely.
3. Propose a detailed plan for ONLY milestone/phase 1 of TASKS.md: module
   layout, exact signatures/types, config defaults, error handling, ordered
   file-by-file work, and the full test list. List every ambiguity or
   contradiction you find between the docs with file:line, propose a
   resolution, and mark it "user must confirm".
4. Stop and wait for the user's approval. No code until the plan is approved.

## Implement loop (only after the plan is approved)

1. Work TASK by TASK within milestone/phase 1 only.
2. For each task: implement it with its tests, then run that task's test
   using the command from TEST_PLAN.md or README.md. If neither specifies
   one, state your assumption and ask; do not default to pytest.
3. Tick its checkbox in TASKS.md.
4. Update MEMORY.md Status / Current task / Next step, and any affected
   docs (PRD, ARCHITECTURE, RULES, TASKS).
5. Propose a commit message and STOP for approval. Commit only after
   approval; then move to the next task.
6. Never start milestone 2 in this session. When milestone 1 is done,
   report changes, risks, and milestone 2's first task, then stop.

## Safety invariants (every session)

- Never print .env or any key/secret.
- No commits, pushes, or changes outside this project dir without explicit
  per-instance approval.
- No dependencies beyond what the docs justify; respect RULES.md.

## Goal (from the design)

{agent_prompt}
"""


class HandoffError(Exception):
    """A handoff failure whose message is already CLI-friendly."""


def collect_pack_files(docs_dir: Path) -> tuple[list[Path], list[str]]:
    """Split docs_dir entries into (allowlisted files, non-allowlisted names)."""
    files: list[Path] = []
    strays: list[str] = []
    for entry in sorted(docs_dir.iterdir()):
        if entry.is_file() and entry.name in PACK_ALLOWLIST:
            files.append(entry)
        else:
            strays.append(entry.name)
    return files, strays


def _canonical(path: Path) -> Path:
    """Symlink/junction-resolved, case-folded path for containment checks."""
    return Path(os.path.normcase(str(path.resolve())))


def validate_target(target: Path, repo_root: Path, force: bool) -> None:
    """Refuse targets inside the Praxis repo, ancestors of it, or non-empty."""
    t = _canonical(target)
    r = _canonical(repo_root)
    if t == r or t in r.parents or r in t.parents:
        raise HandoffError(
            f"error: target {target} is inside the Praxis repo (or is/contains "
            f"it); choose a directory outside {repo_root}"
        )
    if target.exists() and any(target.iterdir()) and not force:
        raise HandoffError(
            f"error: target {target} is not empty; pass --force to "
            f"overwrite-merge into it (extras are kept, never deleted)"
        )
    if shutil.which("git") is None:
        raise HandoffError("error: git not found on PATH")


def _scan_for_secrets(paths: list[Path], root: Path) -> list[tuple[str, str]]:
    """Return (relative path, pattern label) hits among the given files.

    Scopes strictly to files handoff wrote or merged; pre-existing user
    files in a --force target are never read.
    """
    hits: list[tuple[str, str]] = []
    for path in paths:
        if not path.is_file():
            continue
        text = path.read_text(encoding="utf-8", errors="replace")
        for line in text.splitlines():
            for label, pattern in _KEY_PATTERNS:
                m = pattern.search(line)
                if not m:
                    continue
                matched = m.group(0).lower()
                if any(marker in matched for marker in _PLACEHOLDER_MARKERS):
                    continue
                hits.append((str(path.relative_to(root)), label))
                break
    return hits


def build_handoff_prompt(
    title: str, candidate_id: int, agent_prompt_md: str, read_list: str
) -> str:
    return HANDOFF_PROMPT_TEMPLATE.format(
        title=title,
        candidate_id=candidate_id,
        read_list=read_list,
        agent_prompt=agent_prompt_md.strip(),
    )


def _workflow_section(pack_names: set[str]) -> str:
    """The AGENTS.md Workflow section; doc names derived from copied files."""
    read_list = ", ".join(name for name in _READ_ORDER if name in pack_names)
    updates: list[str] = []
    if "TASKS.md" in pack_names:
        updates.append("tick it in TASKS.md")
    if "MEMORY.md" in pack_names:
        updates.append("update MEMORY.md (Status / Current task / Next step)")
    update_step = "; ".join(updates) if updates else "update the status docs"
    return (
        "## Workflow\n"
        f"1. Read the design docs first: {read_list}.\n"
        "2. Plan before writing any code.\n"
        "3. Work one task at a time — never parallelize.\n"
        "4. Work only within the milestone the user approved; never start "
        "the next one without approval.\n"
        f"5. After each task: {update_step}, plus any docs the task "
        "affected.\n"
        "6. Propose a commit message and wait for approval before "
        "committing.\n"
        "7. Never print .env or any key/secret.\n"
        "8. Never push.\n"
    )


def _agents_body(pack_names: set[str], rules_text: str) -> str:
    """Praxis header + Workflow section + RULES.md verbatim."""
    parts = [_PRAXIS_HEADER, _workflow_section(pack_names).rstrip("\n")]
    if rules_text.strip():
        parts.append(rules_text.strip("\n"))
    return "\n\n".join(parts) + "\n"


def _write_generated(target: Path, rel: Path, content: str, notes: list[str]) -> bool:
    """Write a praxis-generated file, keeping a foreign pre-existing one.

    An existing file that carries the Praxis header is regenerated; one
    without it belongs to the user: kept as-is with a one-line note.
    Returns True when the file was written (and is cleaned up on failure).
    """
    path = target / rel
    if path.exists():
        existing = path.read_text(encoding="utf-8", errors="replace")
        if _PRAXIS_HEADER not in existing:
            notes.append(f"note: kept existing {rel.as_posix()} (no Praxis header)")
            return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")
    return True


def _stack_section_text(architecture_text: str) -> str | None:
    """Text under ARCHITECTURE.md's `### Stack` heading, else None."""
    lines = architecture_text.splitlines()
    for i, line in enumerate(lines):
        if _STACK_HEADING_RE.match(line):
            for j in range(i + 1, len(lines)):
                if _ANY_HEADING_RE.match(lines[j]):
                    return "\n".join(lines[i + 1 : j])
            return "\n".join(lines[i + 1 :])
    return None


def _stack_gitignore_lines(pack_files: list[Path]) -> list[str]:
    """Universal gitignore lines plus blocks for the stack the pack describes.

    Stack markers come from ARCHITECTURE.md (its `### Stack` section when
    present, otherwise only strong whole-file markers) and a pack-wide
    SQLite mention; nothing detected means universal lines only.
    """
    arch = next((f for f in pack_files if f.name == "ARCHITECTURE.md"), None)
    detected: set[str] = set()
    haystack = ""
    if arch is not None:
        arch_text = arch.read_text(encoding="utf-8", errors="replace")
        section = _stack_section_text(arch_text)
        markers, haystack = (
            (_STACK_MARKERS, section) if section is not None else (_STRONG_MARKERS, arch_text)
        )
        for stack, patterns in markers.items():
            if any(pattern.search(haystack) for pattern in patterns):
                detected.add(stack)
        if any(pattern.search(haystack) for pattern in _NEXTJS_MARKERS):
            detected.add("nextjs")
    lines = list(GITIGNORE_UNIVERSAL)
    for stack in ("python", "node", "nextjs", "rust"):
        if stack in detected:
            lines.extend(_GITIGNORE_BLOCKS[stack])
    if any(
        _SQLITE_RE.search(f.read_text(encoding="utf-8", errors="replace"))
        for f in pack_files
        if f.suffix == ".md"
    ):
        lines.extend(("*.db", "*.sqlite3"))
    deduped: list[str] = []
    for line in lines:
        if line not in deduped:
            deduped.append(line)
    return deduped


def _merge_gitignore(path: Path, new_lines: list[str]) -> tuple[bytes | None, bool]:
    """Merge new_lines into path; returns (original bytes or None, changed).

    Existing content keeps its line endings (LF or CRLF) and may lack a
    trailing newline; the \"# added by praxis handoff\" marker sits above the
    appended block and appears at most once across reruns.
    """
    if not path.exists():
        path.write_text("\n".join(new_lines) + "\n", encoding="utf-8", newline="\n")
        return None, True
    original = path.read_bytes()
    text = original.decode("utf-8", errors="replace")
    eol = "\r\n" if "\r\n" in text else "\n"
    existing = text.splitlines()
    missing = [line for line in new_lines if line not in existing]
    if not missing:
        return original, False
    if not any(line.strip() == _GITIGNORE_MARKER for line in existing):
        existing.append(_GITIGNORE_MARKER)
    existing.extend(missing)
    path.write_bytes((eol.join(existing) + eol).encode("utf-8"))
    return original, True


def _restore_gitignore(path: Path, original: bytes | None, changed: bool) -> None:
    """Undo a merge on the failure path: delete ours, restore theirs."""
    if not changed:
        return
    if original is None:
        path.unlink(missing_ok=True)
    else:
        path.write_bytes(original)


def run_handoff(
    candidate_id: int,
    target: str | Path,
    *,
    force: bool = False,
    skip_check: bool = False,
    design_root: Path | None = None,
    cursor: bool = False,
) -> int:
    """Export candidate's design docs pack into target. Returns a process exit code."""
    from praxis.discover import get_candidate

    def fail(message: str) -> int:
        print(message, file=sys.stderr)
        return 1

    candidate = get_candidate(candidate_id)
    if candidate is None:
        return fail(f"error: no candidate with id {candidate_id}")

    design = latest_design(candidate_id)
    if design is None:
        return fail(f"error: candidate {candidate_id} has no design")

    passes = load_passes(design)
    missing_pack = [p for p in PACK_PASS_IDS if not (passes.get(p) or "").strip()]
    if missing_pack:
        return fail(
            "error: docs pack incomplete (missing: "
            + ", ".join(missing_pack)
            + f"); run 'praxis plan {candidate_id}' first"
        )

    if not skip_check:
        meta = get_design_meta(design.id) if design.id is not None else {}
        blueprint = latest_blueprint(candidate_id)
        findings = run_checks(
            passes,
            load_facts(),
            stamped=meta.get("pack_version") == PROVENANCE_VERSION,
            blueprint=blueprint.blueprint_md if blueprint is not None else None,
        )
        errors = [f for f in findings if f.severity == SEVERITY_ERROR]
        if errors:
            for f in errors:
                print(f"[ERROR] {f.rule_id} {f.pass_id}: {f.message}")
            return fail(
                f"error: {len(errors)} consistency error(s); "
                f"fix them or pass --skip-check"
            )

    title = (getattr(candidate, "title", "") or f"candidate-{candidate_id}").strip()
    design_path = design_dir(candidate_id, title, root=design_root)
    docs_dir = design_path / "docs"
    if not docs_dir.is_dir():
        return fail(f"error: no docs pack at {docs_dir}; run 'praxis plan {candidate_id}' first")
    agent_prompt_path = design_path / "AGENT_PROMPT.md"
    if not agent_prompt_path.is_file():
        return fail(
            f"error: no AGENT_PROMPT.md at {agent_prompt_path}; "
            f"run 'praxis design {candidate_id}' first"
        )

    pack_files, strays = collect_pack_files(docs_dir)
    if strays and not force:
        return fail(
            f"error: docs/ contains non-pack entries: {', '.join(strays)}; "
            f"remove them or pass --force to copy the {len(PACK_ALLOWLIST)}-file allowlist anyway"
        )

    target_path = Path(target).expanduser()
    repo_root = design_path.parents[1]  # <root>/designs/<NNN>-slug -> <root>
    target_existed = target_path.exists()
    copied: list[Path] = []
    notes: list[str] = []
    generated: list[str] = []
    gitignore_path = target_path / ".gitignore"
    gitignore_original: bytes | None = None
    gitignore_changed = False
    prompt_path = target_path / "HANDOFF_PROMPT.md"
    try:
        validate_target(target_path, repo_root, force)
        target_path.mkdir(parents=True, exist_ok=True)
        for src in pack_files:
            dest = target_path / src.name
            shutil.copy2(src, dest)
            copied.append(dest)
        pack_names = {src.name for src in pack_files}
        read_list = ", ".join(name for name in _READ_ORDER if name in pack_names)
        agent_prompt = agent_prompt_path.read_text(encoding="utf-8")
        prompt_path.write_text(
            build_handoff_prompt(title, candidate_id, agent_prompt, read_list),
            encoding="utf-8",
        )
        copied.append(prompt_path)
        generated.append("HANDOFF_PROMPT.md")

        rules_path = docs_dir / "RULES.md"
        rules_text = (
            rules_path.read_text(encoding="utf-8") if "RULES.md" in pack_names else ""
        )
        if _write_generated(
            target_path, Path("AGENTS.md"), _agents_body(pack_names, rules_text), notes
        ):
            copied.append(target_path / "AGENTS.md")
            generated.append("AGENTS.md")
        if cursor and _write_generated(
            target_path,
            _CURSOR_REL,
            _CURSOR_FRONTMATTER + _agents_body(pack_names, rules_text),
            notes,
        ):
            copied.append(target_path / _CURSOR_REL)
            generated.append(_CURSOR_REL.as_posix())

        gitignore_original, gitignore_changed = _merge_gitignore(
            gitignore_path, _stack_gitignore_lines(pack_files)
        )
        if gitignore_changed:
            generated.append(".gitignore")

        # Final scan: only files handoff wrote or merged (generated files
        # included), never pre-existing user files in a --force target.
        scan_paths = list(copied)
        if gitignore_changed:
            scan_paths.append(gitignore_path)
        hits = _scan_for_secrets(scan_paths, target_path)
        if hits:
            where = ", ".join(f"{path} ({label})" for path, label in hits[:5])
            raise HandoffError(
                f"error: key-like content found in handoff-written files ({where}); "
                "refusing the handoff"
            )
        result = subprocess.run(
            ["git", "init"], cwd=target_path, capture_output=True, text=True, check=False
        )
        if result.returncode != 0:
            raise HandoffError(
                f"error: git init failed in {target_path}: {result.stderr.strip()}"
            )
    except HandoffError as exc:
        # Never leave a half-export (or secret-bearing) tree behind.
        for path in copied:
            path.unlink(missing_ok=True)
        _restore_gitignore(gitignore_path, gitignore_original, gitignore_changed)
        for empty_dir in (target_path / ".cursor" / "rules", target_path / ".cursor"):
            try:
                empty_dir.rmdir()
            except OSError:
                pass
        if not target_existed and target_path.exists():
            shutil.rmtree(target_path, ignore_errors=True)
        return fail(str(exc))

    if strays:
        print(f"note: skipped non-pack docs/ entries: {', '.join(strays)}")
    for note in notes:
        print(note)
    print(
        f"handoff ready: {target_path} "
        f"({len(pack_files)} pack files + {', '.join(generated)}, git initialized)"
    )
    print(f"next: open a coding agent in {target_path} and paste HANDOFF_PROMPT.md")
    return 0
